/**
 * Menghitung indeks hari ini berdasarkan selisih hari kalender sejak 1 Januari 2025.
 * Setiap pergantian hari (pukul 00:00), indeks otomatis bertambah 1 dan memutar ayat berikutnya.
 */
export function getTodayVerseIndex(date: Date = new Date()): number {
  const baseDate = new Date(2025, 0, 1);
  const midnight = new Date(date.getFullYear(), date.getMonth(), date.getDate());
  const diffDays = Math.floor(
    (midnight.getTime() - baseDate.getTime()) / (1000 * 60 * 60 * 24)
  );
  return Math.abs(diffDays) % DAILY_VERSES.length;
}

/**
 * Mendapatkan ayat Alkitab hari ini.
 */
export function getTodayVerse(date: Date = new Date()): BibleVerse {
  const index = getTodayVerseIndex(date);
  return DAILY_VERSES[index];
}

/**
 * Mendapatkan ayat berdasarkan indeks tertentu (untuk tombol ganti/acak).
 */
export function getVerseByIndex(index: number): BibleVerse {
  const normalizedIndex =
    ((index % DAILY_VERSES.length) + DAILY_VERSES.length) % DAILY_VERSES.length;
  return DAILY_VERSES[normalizedIndex];
}

